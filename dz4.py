# Задача 4.1
"""
Дана строка. Посчитать длинную последовательность подряд идущих букв "н". Заменить их на восклицательные знаки,
вывести новую строку, и количество подря идущих букв "н"
"""

str = input() # ввод строки
str2 = '' # инициируем пустую строку

for i in range(len(str)): # перебераем в цикле все символы строки
    if str[i] == "н":# если встречаем н, то
        str2 += str[i] # добавляем н к строке str2 (вначале она пустая)
    else:
        str2 += " "  # если не встречаем н, то добавляем к строке str2 пробел  
str_list2 = str2.split() # преобразуем строку с пробелами в список      
# цикл определения максимальной последовательности "н"
max_ = 0
for elem in str_list2: 
    if len(elem) > max_: 
        max_ = len(elem)
        max_str = elem # запоминаем подстроку с максимальным повторением "н"
index = str.find(max_str) # определяем индекс вхождения подстроки с максимальным повторением "н"
        
str = str[:index] + '!'* max_ + str[index + max_:] 

print(str)
print(f"Самая длинная последовательность н = {max_} ") 

