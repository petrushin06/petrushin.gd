# Задача 4.3
"""
Дана строка. Вывести все слова, начинающиеся на букву "а" и слова оканчивающие на букву "я". Например: Абстракция,
авария, аллея
"""

str = input().split() # вводим слова в список
# цикл перебора слов в списке
for i in str: 
    i = i.lower() # приводим буквы в слове к нижнему регистру (a == A)
    if i[0] == "а" and i[-1] == "я":
        print(i, end = ' ')