# Задача 7.1
"""
Напишите функцию read_last(lines, file), которая будет открывать определенный файл file и выводить на печать построчно
последние строки в количестве lines (на всякий случай проверим, что задано положительное целое число). Протестируем
функцию на файле article.txt со следующим содержимым:
Вечерело
Жужжали мухи
Светил фонарик
Кипела вода в чайнике
Венера зажглась на небе
Деревья шумели
Тучи разошлись
Листва зеленела
"""
# Для начала надо создать текстовый файл, для тестирования возьмем article.txt с наполнением см. по тексту выше
def read_last(lines, file):
    with open(file, 'r', encoding='utf-8') as f: # закрытие файла происходит автоматически после завершения блока кода работа с файлом
        sp =  f.readlines() # выводим список всех прочитанных строк из файла
        if lines > 0:
            for i in range(len(sp)-lines, len(sp)):
                print(sp[i].rstrip("\n")) # печатаем сроки, отрезая "\n" справа от каждой строки функцией rsstrip
        else:
            print("Количество строк должно быть числом положительным") 

def main():
    print("Введите количество последний строк текстового файла")
    lines = int(input())
    read_last(lines,"Gera/article.txt") # вместо Gera надо прописать ближайшую к файлу папку (относительный путь)

if __name__ == '__main__':
    main()


