"""
4. Составьте программу - простейший редактор текстовых файлов. Алгоритм работы программы:
1. Программа предлагает ввести имя будущего файла. Записывает его, присваивая расширение .txt.
2. Программа предлагает записать строку в файл. При каждом нажатии кнопки ENTER происходит запись строки и переход
на новую строчку.
3. Если строка пустая или спец. символ - программа сохраняет файл.
"""


# функция создания текстового файла
def file_create():
    # создание файла
    print("Введите имя файла")
    name_file = input()
    name_file += ".txt" # добавляем к имени файла расширение .txt
    text_file = open(name_file, 'x')  # создаем файл
    text_file.close() # закрываем файл (сохраняем)
    return name_file # возвращаем имя файла
  
# главная функция
def main():
    name = file_create() # запускаем функцию создания текстового файла и передаем имя это файла переменной "name"
    text_file = open(name, 'a') # открываем файл для дозаписи
    print("Введите текст")
    text = input()
    # основной рабочий цикл программы
    while text != "" and text != "exit": # выходим из программы, если строка пустая или введено слово "exit"
        text_file.write(text + "\n") # записываем введенную строку с добавленным окончание "\n" (перенос строки) в файл
        text = input()
    text_file.close()  # закрываем файл (сохраняем)


if __name__ == '__main__':
    main()   